#!/usr/bin/env bash
# Routing benchmark: Muntin against Flare alone, by route count
# (bench/routing/bench_routing.mojo says what it measures). Not run by CI.
#
#   ./scripts/bench_routing.sh [RUNS] [N...]
#
# RUNS is the number of timed runs per case (default 15; an even count
# reports the mean of the two middle runs as the median); the route counts
# (each at least 2) default to 10 100. 500 and 1000 are named explicitly:
# bench_comptime_router.mojo alone builds for about 9 and 55 minutes there.
# For each N it writes the route table module under build/bench_routing/N,
# builds both programs (default optimization, -O3) in the `flare`
# environment, prints each build's time and runs them,
# pinned with taskset, where it exists (Linux), to the last CPU this process
# may run on (Cpus_allowed_list in /proc/self/status).
set -euo pipefail
cd "$(dirname "$0")/.."

runs="${1:-15}"
shift || true
# Decimal integers only, no leading zero: bash reads 08 as octal.
if ! [[ $runs =~ ^[1-9][0-9]*$ ]]; then
    echo "error: RUNS must be an integer of at least 1: $runs" >&2
    exit 1
fi
counts=("$@")
if ((${#counts[@]} == 0)); then
    counts=(10 100)
fi

FLARE=(pixi run --frozen -e flare mojo)
"${FLARE[@]}" --version
pixi list --frozen -e flare '^flare$' | tail -n 1

for n in "${counts[@]}"; do
    if ! [[ $n =~ ^[1-9][0-9]*$ ]] || ((n < 2)); then
        echo "error: route count must be an integer of at least 2: $n" >&2
        exit 1
    fi
done

body_of() { # I N: the body route I of N answers
    if (($1 == 0)); then
        echo first
    elif (($1 == $2 - 1)); then
        echo last
    else
        echo ok
    fi
}

gen_routes() { # N DIR: writes DIR/routes.mojo with N GET routes
    local n=$1 dir=$2
    mkdir -p "$dir"
    {
        echo '"""Generated by scripts/bench_routing.sh; do not edit."""'
        echo
        echo 'from flare.http import ComptimeRoute, ok'
        echo 'from flare.http import Request as FlareRequest'
        echo 'from flare.http import Response as FlareResponse'
        echo 'from muntin import App'
        echo
        echo "comptime N = $n"
        echo
        # The first and last routes answer their own body, so the benchmark
        # checks which route answered (harness.cases).
        for body in first ok last; do
            echo "def muntin_$body() -> String:"
            echo "    return \"$body\""
            echo
            echo "def flare_$body(req: FlareRequest) raises -> FlareResponse:"
            echo "    return ok(\"$body\")"
            echo
        done
        echo 'def flare_handler(i: Int) -> def(FlareRequest) raises thin -> FlareResponse:'
        echo '    if i == 0:'
        echo '        return flare_first'
        echo "    if i == $((n - 1)):"
        echo '        return flare_last'
        echo '    return flare_ok'
        echo
        echo 'def register(mut app: App):'
        for ((i = 0; i < n; i++)); do
            echo "    app.get[\"/api/r$i/items\"](muntin_$(body_of "$i" "$n"))"
        done
        echo
        echo 'comptime FLARE_ROUTES: List[ComptimeRoute] = ['
        for ((i = 0; i < n; i++)); do
            echo "    ComptimeRoute(\"GET\", \"/api/r$i/items\", flare_$(body_of "$i" "$n")),"
        done
        echo ']'
    } >"$dir/routes.mojo"
}

pin=()
if command -v taskset >/dev/null && [[ -r /proc/self/status ]]; then
    # The allowed set, such as 0-3 or 24-27,30: its last CPU. nproc counts
    # the allowed CPUs and is not one of their numbers.
    allowed="$(sed -n 's/^Cpus_allowed_list:[[:space:]]*//p' /proc/self/status)"
    cpu="${allowed##*[,-]}"
    if [[ $cpu =~ ^[0-9]+$ ]]; then
        pin=(taskset -c "$cpu")
    fi
fi

for n in "${counts[@]}"; do
    dir="build/bench_routing/$n"
    gen_routes "$n" "$dir"
    for prog in bench_routing bench_comptime_router; do
        start=$(date +%s)
        "${FLARE[@]}" build -I src -I adapters/flare -I bench/routing -I "$dir" \
            "bench/routing/$prog.mojo" -o "$dir/$prog"
        echo "# N=$n $prog built in $(($(date +%s) - start)) s"
    done
    for prog in bench_routing bench_comptime_router; do
        ${pin[@]+"${pin[@]}"} "./$dir/$prog" "$runs"
    done
done
