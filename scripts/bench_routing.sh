#!/usr/bin/env bash
# Routing benchmark: Muntin against Flare alone, by route count
# (bench/routing/bench_routing.mojo says what it measures). Not run by CI.
#
#   ./scripts/bench_routing.sh [RUNS] [N...]
#
# RUNS is the number of timed runs per case (default 15); the route counts
# default to 10 100 500 1000. For each N it writes the route table module
# under build/bench_routing/N, builds both programs (default optimization,
# -O3) in the `flare` environment, prints each build's time and runs them,
# pinned to one CPU with taskset where it exists (Linux). Building
# bench_comptime_router.mojo grows steeply with N: minutes at 500 routes.
set -euo pipefail
cd "$(dirname "$0")/.."

runs="${1:-15}"
shift || true
counts=("$@")
if ((${#counts[@]} == 0)); then
    counts=(10 100 500 1000)
fi

FLARE=(pixi run --frozen -e flare mojo)
"${FLARE[@]}" --version
pixi list --frozen -e flare '^flare$' | tail -n 1

gen_routes() { # N DIR: writes DIR/routes.mojo with N GET routes
    local n=$1 dir=$2
    mkdir -p "$dir"
    {
        echo '"""Generated by scripts/bench_routing.sh; do not edit."""'
        echo
        echo 'from flare.http import ComptimeRoute, ok'
        echo 'from flare.http import Request as FlareRequest'
        echo 'from flare.http import Response as FlareResponse'
        echo 'from muntin import App'
        echo
        echo "comptime N = $n"
        echo
        echo 'def muntin_ok() -> String:'
        echo '    return "ok"'
        echo
        echo 'def flare_ok(req: FlareRequest) raises -> FlareResponse:'
        echo '    return ok("ok")'
        echo
        echo 'def register(mut app: App):'
        for ((i = 0; i < n; i++)); do
            echo "    app.get[\"/api/r$i/items\"](muntin_ok)"
        done
        echo
        echo 'comptime FLARE_ROUTES: List[ComptimeRoute] = ['
        for ((i = 0; i < n; i++)); do
            echo "    ComptimeRoute(\"GET\", \"/api/r$i/items\", flare_ok),"
        done
        echo ']'
    } >"$dir/routes.mojo"
}

pin=()
if command -v taskset >/dev/null; then
    pin=(taskset -c "$(($(nproc) - 1))")
fi

for n in "${counts[@]}"; do
    dir="build/bench_routing/$n"
    gen_routes "$n" "$dir"
    for prog in bench_routing bench_comptime_router; do
        start=$(date +%s)
        "${FLARE[@]}" build -I src -I adapters/flare -I bench/routing -I "$dir" \
            "bench/routing/$prog.mojo" -o "$dir/$prog"
        echo "# N=$n $prog built in $(($(date +%s) - start)) s"
    done
    for prog in bench_routing bench_comptime_router; do
        ${pin[@]+"${pin[@]}"} "./$dir/$prog" "$runs"
    done
done
